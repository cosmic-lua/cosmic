/*
 * The Linux system call numbers of the two architectures the filter
 * (core/promises.c) is written for, by name, from the kernel's own
 * asm/unistd_64.h of the pinned zig's headers (Linux 6.18) for each:
 * x86-linux-any/asm/unistd_64.h and aarch64-linux-any/asm/unistd_64.h.
 * They are carried here, not read from the headers of the host a core
 * is built on, so a filter for either architecture is the same bytes
 * from any host, and a sample of them is held to the host's headers
 * where there is one (promises.c's `_Static_assert`s). aarch64 has no number for a call
 * x86_64 kept from before the generic table (open, fork, select, ...),
 * so its list is a subset of x86_64's, and the names of the calls are
 * the first list's.
 *
 * The highest number in either list, 471, is the highest the table has
 * been reviewed to: PROMISE_CALLS_REVIEWED (core/promises.h) is one past
 * it. A call numbered above it is answered ENOSYS, whatever the kernel
 * by then makes of it.
 */

